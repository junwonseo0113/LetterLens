// Document names as written on a letter (e.g. an HRA checklist). Only
// exact known phrases are translated; anything else is shown as written.
const DOC_TEXT_KEY = {
  "proof of income": "docText_income",
  "proof of residence": "docText_residence",
  id: "docText_id",
};

export function documentText(language, text) {
  const key = DOC_TEXT_KEY[text.trim().toLowerCase()];
  return key ? t(language, key) : text;
}
