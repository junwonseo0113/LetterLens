export function t(language, key, vars) {
  const text = UI_STRINGS[language]?.[key] ?? UI_STRINGS.en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "") : text;
}

